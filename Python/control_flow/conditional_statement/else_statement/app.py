score = int(input("Enter your Score:"))

if score >= 80:
    print("Congratulations you got an A")

elif score >= 70:
    print("Good result you got B")

elif score >= 60:
    print("Pass, try hard next semester")

elif score >= 50:
    print("You narrowly passed your exam, you need read more")

else:
    print("You failed your exams")